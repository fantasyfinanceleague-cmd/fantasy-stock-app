-- ============================================================================
-- Account deletion (7/10): takeover codes and take_over_team
-- ============================================================================
-- Plan: docs/plans/2026-10-21-account-deletion.md, decisions 5, 13, 14 and
-- "Takeover". Giorgio, 2026-10-21, on the team after a takeover: "keep the teams
-- record just the owner is gone". The new manager inherits the seat whole
-- (roster, cash, record, waiver position, past weeks under their name).
--
-- 1. league_invites gains kind ('invite' | 'takeover', default 'invite') and
--    seat_user_id (the deleted seat's user id; set exactly when kind =
--    'takeover', a CHECK). One PENDING takeover code per seat (a partial unique
--    index). A takeover code is accepted when the seat is taken; it is dead
--    after the season (take_over_team checks the window at use).
--    league_invites_insert_commissioner ([P1], 20260712000003) is narrowed to
--    kind = 'invite': a client may never write a takeover row directly, so every
--    takeover code is server-generated by create_takeover_invite below. A
--    takeover code lives ONLY here: join_league_by_code and
--    invite_preview_lookup (re-created in 20261125000008) resolve kind =
--    'invite' rows only, and _takeover_check never reads leagues.invite_code or
--    an ordinary invite.
-- 2. league_notifications.kind += 'seat_taken_over' (to the commissioner; the
--    join-league edge function pushes it). The CHECK re-lists every live kind
--    (notification_kinds_monotonic.test.ts).
-- 3. enforce_league_draft_order_rows (20261013000000) refuses every change to a
--    locked order, for every role. It gains ONE allowed transition: on the
--    service path (auth.uid() IS NULL), an UPDATE that changes only user_id
--    (same league, same position) away from a seat whose league_members row is
--    deleted (deleted_at IS NOT NULL). take_over_team re-points the order row
--    FIRST, while the seat is still marked deleted. Nothing else is loosened.
-- 4. create_takeover_invite(p_league_id, p_seat_user_id) -> jsonb. AUTHENTICATED:
--    the caller is auth.uid() and must be the league's commissioner, so no id
--    is forgeable. Only for a deleted seat, from draft complete through the
--    playoffs (decision 14). Returns the seat's pending code if it has one.
-- 5. Failed-guess accounting (a takeover code is a bearer capability):
--    takeover_guess_limits + takeover_guess_try_lock, the invite_preview_lookup
--    pattern. 10 misses an hour per user (the main control) and a HIGH global
--    backstop of 2,000 an hour, checked first; a
--    contended lock refuses ('rate_limited'), never queues.
-- 6. _takeover_check(p_code, p_user_id, p_lock) -> jsonb, owner only: the ONE
--    eligibility check behind both functions below, so the preview and the
--    takeover can never disagree. The league comes from the code (the takeover
--    link carries only the code). CODE FIRST, matched EXACTLY (codes are issued
--    ^[A-Z0-9]{10}$ by _renewal_invite_code from gen_random_uuid(), a CSPRNG;
--    50 bits; valid 14 days; single use). In order:
--      the limiter                                     else 'rate_limited'
--      a PENDING, unexpired takeover code, exactly     a used one -> 'taken';
--                                                      anything else -> 'invalid_code'
--                                                      (unknown, expired, revoked, an
--                                                      ordinary invite, a league's own
--                                                      code: identical, and a miss)
--      its league still exists (locked when p_lock)   else 'gone'
--      the caller is a live account (an auth.users row and no deletion ledger
--      row)                                            else 'not_eligible'
--      the code is still pending under the lock        else 'taken'
--      the seat row still exists in that league        else 'taken'
--      the seat is deleted                             else 'not_deleted'
--      draft completed, season not completed           else 'window'
--      the caller holds no row in this league          else 'already_member'
-- 7. takeover_preview(p_code, p_user_id) -> jsonb. SERVICE ROLE ONLY. No lock and
--    no write except the miss counter: {ok: true, league_name, wins, losses, rank} for the
--    seat the code points to (league_standings_ranked's rank), or {ok: false,
--    reason}. No ids, no other member, nothing else.
-- 8. take_over_team(p_code, p_user_id) -> jsonb. SERVICE ROLE ONLY (the
--    join-league edge function's `takeover` action, user id from the JWT).
--    Runs _takeover_check WITH locks (the league, then the invite, then the
--    seat, FOR UPDATE). Then, in this transaction, every row of the old id in
--    THAT league moves to the caller: league_draft_order (first; see 3),
--    league_members (deleted_at NULL, joined_at kept, role member), matchups
--    (team1, team2, winner), league_standings, week_snapshots, drafts, trades,
--    league_seasons (champion, runner-up), and, when those tables exist, the
--    waiver-wire plan's waiver_order and claims. The invite is marked accepted;
--    one seat_taken_over notice goes to the commissioner. Then it VERIFIES that
--    no row of the old id is left in the league (a breach raises and rolls
--    back). A second caller waits on the league lock, then sees the accepted
--    invite: 'taken'. league_participant_display_name then resolves the new
--    manager's live name on every past week.
--
-- PROVISIONAL TIMESTAMP: see 20261125000000.
--
-- POST-PUSH CHECKS (SQL editor):
--   SELECT relrowsecurity, relacl FROM pg_class WHERE oid = 'public.takeover_guess_limits'::regclass;
--   -- t, owner only
--   SELECT proname, proacl, prosecdef, proconfig FROM pg_proc
--    WHERE proname IN ('take_over_team', 'takeover_preview', '_takeover_check', 'takeover_guess_try_lock',
--                      'create_takeover_invite', 'enforce_league_draft_order_rows');
