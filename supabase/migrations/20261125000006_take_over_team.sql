-- ---- 3. the draft-order lock lets a deleted seat be re-pointed --------------------
create or replace function public.enforce_league_draft_order_rows()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_league uuid := case when tg_op = 'DELETE' then old.league_id else new.league_id end;
  v_state  text;
begin
  select state into v_state from public.league_draft_order_meta where league_id = v_league;

  -- No meta (it is being cascaded away) or still open: free. The only writers
  -- are the definer functions in this migration.
  if v_state is null or v_state = 'open' then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  -- 20261125000006: take_over_team hands a deleted manager's seat to a new
  -- manager. On the service path only, the ONE change allowed to a set or locked
  -- order is re-pointing a deleted seat's row: same league, same position, only
  -- user_id moves, and the old id's league_members row is marked deleted.
  if tg_op = 'UPDATE' and auth.uid() is null
     and new.league_id = old.league_id and new.position = old.position
     and new.user_id is distinct from old.user_id
     and exists (select 1 from public.league_members m
                  where m.league_id = old.league_id and m.user_id = old.user_id
                    and m.deleted_at is not null) then
    return new;
  end if;

  if tg_op = 'DELETE' then
    -- A league delete cascades through here: allowed once the league is gone.
    if v_state = 'locked' and exists (select 1 from public.leagues where id = v_league) then
      raise exception 'draft_order_locked: the draft has started; the draft order cannot change'
        using errcode = '22023';
    end if;
    return old;   -- finalized: a leaver is removed
  end if;

  if v_state = 'locked' then
    raise exception 'draft_order_locked: the draft has started; the draft order cannot change'
      using errcode = '22023';
  end if;

  -- finalized: append past the end, or shift a row UP to close a gap. Nothing
  -- else — no reordering after draft_date − 1h.
  if tg_op = 'INSERT' then
    if exists (select 1 from public.league_draft_order
                where league_id = new.league_id and position >= new.position) then
      raise exception 'draft_order_finalized: after the order is set, members can only be appended'
        using errcode = '22023';
    end if;
    return new;
  end if;

  if new.league_id = old.league_id and new.user_id = old.user_id and new.position < old.position then
    return new;
  end if;
  raise exception 'draft_order_finalized: the draft order is set and cannot be rearranged'
    using errcode = '22023';
end;
$$;

revoke all on function public.enforce_league_draft_order_rows()           from public, anon, authenticated, service_role;

-- ---- 4. create_takeover_invite (the commissioner) ------------------------------------
create or replace function public.create_takeover_invite(p_league_id uuid, p_seat_user_id text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_caller text := auth.uid()::text;
  v_l      public.leagues%rowtype;
  v_seat   text;
  v_code   text;
begin
  if v_caller is null then
    raise exception 'not authenticated' using errcode = '42501';
  end if;
  if p_league_id is null or p_seat_user_id is null then
    raise exception 'invalid_arguments' using errcode = '22023';
  end if;

  select * into v_l from public.leagues where id = p_league_id for update;
  -- A missing league and a non-commissioner get the SAME answer: no existence oracle.
  if not found or v_l.commissioner_id is distinct from v_caller then
    return jsonb_build_object('status', 'refused', 'reason', 'not_commissioner');
  end if;
  if v_l.draft_status is distinct from 'completed' or v_l.season_status = 'completed' then
    return jsonb_build_object('status', 'refused', 'reason', 'window');
  end if;
  select m.user_id into v_seat from public.league_members m
   where m.league_id = p_league_id and lower(m.user_id) = lower(p_seat_user_id)
     and m.deleted_at is not null;
  if not found then
    return jsonb_build_object('status', 'refused', 'reason', 'not_deleted');
  end if;

  -- A pending code past its expiry is dead: retire it, so the seat can have a fresh one
  -- (the one-pending-per-seat index would otherwise hold the slot).
  update public.league_invites set status = 'expired'
   where league_id = p_league_id and kind = 'takeover' and status = 'pending'
     and lower(seat_user_id) = lower(v_seat) and expires_at <= now();
  select i.code into v_code from public.league_invites i
   where i.league_id = p_league_id and i.kind = 'takeover' and i.status = 'pending'
     and lower(i.seat_user_id) = lower(v_seat);
  if found then
    return jsonb_build_object('status', 'ok', 'code', v_code, 'created', false);
  end if;

  -- CSPRNG: each of the 10 symbols is byte 0 of a fresh gen_random_uuid()
  -- (pg_strong_random), mod 32: 50 bits, never derived from any id. Unique across
  -- leagues.invite_code and league_invites.code.
  v_code := public._renewal_invite_code();
  insert into public.league_invites (league_id, inviter_id, invited_identifier, code, status, kind, seat_user_id,
                                     expires_at)
  values (p_league_id, v_caller, 'takeover', v_code, 'pending', 'takeover', v_seat,
          now() + interval '14 days');   -- the takeover code's TTL
  return jsonb_build_object('status', 'ok', 'code', v_code, 'created', true);
end;
$$;

comment on function public.create_takeover_invite(uuid, text) is
  'Account deletion (2026-10-21): the commissioner''s "Find a new manager" code for a deleted seat. One pending '
  'code per seat, valid 14 days, single use. Caller = auth.uid().';

revoke all on function public.create_takeover_invite(uuid, text) from public, anon, service_role;
grant execute on function public.create_takeover_invite(uuid, text) to authenticated;

-- ---- 5. failed-guess accounting --------------------------------------------------
-- A takeover code is a bearer capability, and the edge limiters alone can be farmed
-- with free accounts, so the database counts misses itself (invite_preview_lookup's
-- pattern, 20261124000000): a per-user lockout after 10 misses an hour (the main
-- control) and a GLOBAL backstop of 2,000 misses an hour. Both are checked BEFORE the lookup and do not
-- bump, so a locked-out caller cannot spend more of the budget (valid codes are
-- refused too while locked out). Only an unmatched code bumps. The check-then-bump
-- runs one caller at a time behind a TRY advisory lock: a caller that cannot take
-- it at once is refused, never queued (FAIL CLOSED). Its own table, pruned to two
-- hours on every call; RLS on, no policies, no grants (not even service_role).
create table if not exists public.takeover_guess_limits (
  subject      text        not null,   -- 'miss-all' | 'miss-user:<uuid>'
  window_start timestamptz not null,   -- the hour the count belongs to
  hits         int         not null default 0,
  primary key (subject, window_start)
);
alter table public.takeover_guess_limits enable row level security;
revoke all on table public.takeover_guess_limits from public, anon, authenticated, service_role;

-- Its own function so the refusal is testable (PGlite has one session, where an
-- advisory lock is re-entrant). Internal: no API role may call it.
create or replace function public.takeover_guess_try_lock()
returns boolean
language sql
volatile
set search_path = public, pg_temp
as $$
  select pg_try_advisory_xact_lock(hashtext('takeover_guess'))
$$;

revoke all on function public.takeover_guess_try_lock() from public, anon, authenticated, service_role;

-- ---- 6. the one eligibility check ------------------------------------------------
create or replace function public._takeover_check(p_code text, p_user_id uuid, p_lock boolean)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  -- The per-user lockout is the main control. The global ceiling is only a backstop
  -- against a flood, so it is set HIGH on purpose: free accounts could otherwise trip
  -- a low one on purpose and lock every real taker out for an hour (W3 security
  -- review, round 5). 2,000 misses an hour still bounds a guesser to ~2^-39 per hour
  -- against a 50-bit code space.
  c_miss_per_user constant int := 10;
  c_miss_global   constant int := 2000;
  v_hour   timestamptz := date_trunc('hour', now());
  v_all    int;
  v_mine   int;
  v_inv    public.league_invites%rowtype;
  v_l      public.leagues%rowtype;
  v_seat   public.league_members%rowtype;
begin
  if p_code is null or p_user_id is null or p_lock is null then
    raise exception 'invalid_arguments' using errcode = '22023';
  end if;

  -- ---- the limiter, before anything else ----
  if not public.takeover_guess_try_lock() then
    return jsonb_build_object('ok', false, 'reason', 'rate_limited');
  end if;
  delete from public.takeover_guess_limits where window_start < now() - interval '2 hours';
  select coalesce(sum(hits), 0) into v_all
    from public.takeover_guess_limits where subject = 'miss-all' and window_start = v_hour;
  select coalesce(sum(hits), 0) into v_mine
    from public.takeover_guess_limits where subject = 'miss-user:' || p_user_id::text and window_start = v_hour;
  if v_all >= c_miss_global or v_mine >= c_miss_per_user then
    return jsonb_build_object('ok', false, 'reason', 'rate_limited');
  end if;

  -- ---- CODE FIRST: exact equality, a live takeover code only ----
  -- Nothing is normalized (codes are issued ^[A-Z0-9]{10}$; the client upper-cases and
  -- trims). An unknown, expired or revoked code, an ordinary invite code and a league's
  -- own invite_code all take this one path and get the identical 'invalid_code'. Every
  -- reason below is reachable ONLY after a match, so no league or seat can be
  -- enumerated. The one exception, by the plan's rule ("a second taker gets 'already
  -- taken'"): a USED code answers 'taken' and is not a miss. It reveals only that the
  -- code was used, never whether a league or seat exists.
  select * into v_inv from public.league_invites i
   where i.code = p_code and i.kind = 'takeover' and i.status = 'pending' and i.expires_at > now();
  if not found then
    if exists (select 1 from public.league_invites i
                where i.code = p_code and i.kind = 'takeover' and i.status = 'accepted') then
      return jsonb_build_object('ok', false, 'reason', 'taken');
    end if;
    insert into public.takeover_guess_limits (subject, window_start, hits)
    values ('miss-all', v_hour, 1), ('miss-user:' || p_user_id::text, v_hour, 1)
    on conflict (subject, window_start) do update set hits = public.takeover_guess_limits.hits + 1;
    return jsonb_build_object('ok', false, 'reason', 'invalid_code');
  end if;

  -- The league lock serializes every taker (and a league delete); then the invite and
  -- the seat are re-read under their own locks.
  if p_lock then
    select * into v_l from public.leagues where id = v_inv.league_id for update;
  else
    select * into v_l from public.leagues where id = v_inv.league_id;
  end if;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'gone');
  end if;

  -- A live account only: never a forged id, never one being deleted.
  if not exists (select 1 from auth.users u where u.id = p_user_id)
     or exists (select 1 from public.account_deletions d where d.user_id = p_user_id) then
    return jsonb_build_object('ok', false, 'reason', 'not_eligible');
  end if;

  if p_lock then
    select * into v_inv from public.league_invites i where i.id = v_inv.id for update;
    if not found or v_inv.status <> 'pending' then
      return jsonb_build_object('ok', false, 'reason', 'taken');   -- used while we waited for the lock
    end if;
  end if;

  if p_lock then
    select * into v_seat from public.league_members m
     where m.league_id = v_l.id and m.user_id = v_inv.seat_user_id for update;
  else
    select * into v_seat from public.league_members m
     where m.league_id = v_l.id and m.user_id = v_inv.seat_user_id;
  end if;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'taken');
  end if;
  if v_seat.deleted_at is null then
    return jsonb_build_object('ok', false, 'reason', 'not_deleted');
  end if;
  if v_l.draft_status is distinct from 'completed' or v_l.season_status = 'completed' then
    return jsonb_build_object('ok', false, 'reason', 'window');
  end if;
  if exists (select 1 from public.league_members m
              where m.league_id = v_l.id and lower(m.user_id) = lower(p_user_id::text)) then
    return jsonb_build_object('ok', false, 'reason', 'already_member');
  end if;

  return jsonb_build_object('ok', true, 'league_id', v_l.id, 'league_name', v_l.name,
    'commissioner_id', v_l.commissioner_id, 'invite_id', v_inv.id, 'seat_user_id', v_seat.user_id);
end;
$$;

revoke all on function public._takeover_check(text, uuid, boolean) from public, anon, authenticated, service_role;

-- ---- 7. takeover_preview (what the landing shows before "Take the team") -----------
create or replace function public.takeover_preview(p_code text, p_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_chk  jsonb;
  v_r    record;
begin
  v_chk := public._takeover_check(p_code, p_user_id, false);
  if not (v_chk ->> 'ok')::boolean then
    return jsonb_build_object('ok', false, 'reason', v_chk ->> 'reason');
  end if;
  select s.wins, s.losses, s.rank into v_r
    from public.league_standings_ranked((v_chk ->> 'league_id')::uuid) s
   where s.user_id = v_chk ->> 'seat_user_id';
  return jsonb_build_object(
    'ok', true,
    'league_name', v_chk ->> 'league_name',
    'wins', coalesce(v_r.wins, 0),
    'losses', coalesce(v_r.losses, 0),
    'rank', v_r.rank);   -- NULL when the league keeps no standings (a duration league)
end;
$$;

