/** Display names counted back from the final (Giorgio, 2026-09-29). */
const ROUND_NAMES_FROM_FINAL = ['Final', 'Semifinals', 'Quarterfinals', 'Round of 16'] as const;

/**
 * Display label per round (index 0 = round 1), or null when P is invalid or
 * the bracket is longer than the named rounds (W > 4, impossible while leagues
 * cap at 16 managers). A first round that has byes is the "Wild card" round.
 * MIRRORED byte-for-byte by the client helpers (apps/mobile/lib/playoffs.ts,
 * apps/web/src/utils/playoffs.js); apps/mobile/tests-deno/playoffs.test.ts
 * pins all three to each other.
 */
export function playoffRoundLabels(p: number): string[] | null {
  if (!isValidPlayoffTeams(p)) return null;
  const { weeks, byes } = playoffShape(p);
  if (weeks > ROUND_NAMES_FROM_FINAL.length) return null;
  const rounds = Array.from({ length: weeks }, (_, i) => ROUND_NAMES_FROM_FINAL[weeks - 1 - i] as string);
  if (byes > 0 && weeks > 1) rounds[0] = 'Wild card';
  return rounds;
}

/** The STRUCTURAL code stored in matchups.playoff_round, by distance from the
 * final. Not display copy: installed app builds and the season-completion check
 * read it. Display labels come from playoffRoundLabels. */
export type PlayoffRoundCode = 'finals' | 'semi' | 'quarter' | 'round_of_16';
const ROUND_CODES_FROM_FINAL: readonly PlayoffRoundCode[] = ['finals', 'semi', 'quarter', 'round_of_16'];

export function playoffRoundCode(round: number, weeks: number): PlayoffRoundCode {
  const fromFinal = weeks - round;
  if (!Number.isInteger(fromFinal) || round < 1 || fromFinal < 0 || fromFinal >= ROUND_CODES_FROM_FINAL.length) {
    throw new RangeError(`no round code for round ${round} of ${weeks}`);
  }
  return ROUND_CODES_FROM_FINAL[fromFinal];
}
