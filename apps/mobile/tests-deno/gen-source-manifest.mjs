#!/usr/bin/env node
// Writes tests-deno/sourceManifest.generated.ts: every app source file
// (app/, components/, lib/, constants/; .ts/.tsx; no __tests__) imported AS
// TEXT, so tests-deno can scan the whole app's source with no --allow-read
// (`deno test .` stays flag-free; raw-imports is on in deno.json).
// Used by no-placeholder-copy.test.ts (no "[new copy" may reach a player).
//
//   node tests-deno/gen-source-manifest.mjs           regenerate
//   node tests-deno/gen-source-manifest.mjs --check   exit 1 if stale (a file added/removed)
//
// Re-run after adding or removing a source file, like scripts/gen-architecture.mjs.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const ROOTS = ['app', 'components', 'lib', 'constants'];
const OUT = join(here, 'sourceManifest.generated.ts');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name === '__tests__' || name === 'node_modules') continue;
      out.push(...walk(p));
    } else if (/\.(ts|tsx)$/.test(name) && !/\.d\.ts$/.test(name)) {
      out.push(relative(root, p).split('\\').join('/'));
    }
  }
  return out;
}

const files = ROOTS.flatMap((r) => walk(join(root, r)));
const lines = [
  '// GENERATED by tests-deno/gen-source-manifest.mjs. Do not edit by hand:',
  '// run `node tests-deno/gen-source-manifest.mjs` after adding or removing a source file.',
  ...files.map((f, i) => `import s${i} from '../${f}' with { type: 'text' };`),
  '',
  '/** Every app source file, by path relative to apps/mobile, as text. */',
  'export const SOURCES: Record<string, string> = {',
  ...files.map((f, i) => `  '${f}': s${i},`),
  '};',
  '',
];
const text = lines.join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
  if (current !== text) {
    const had = new Set([...current.matchAll(/^ {2}'([^']+)': s\d+,$/gm)].map((m) => m[1]));
    const now = new Set(files);
    for (const f of files) if (!had.has(f)) console.log(`+ ${f}`);
    for (const f of had) if (!now.has(f)) console.log(`- ${f}`);
    console.log('sourceManifest.generated.ts is stale: run node tests-deno/gen-source-manifest.mjs');
    process.exit(1);
  }
  console.log(`sourceManifest.generated.ts is current (${files.length} files).`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${relative(root, OUT)} (${files.length} files)`);
}
